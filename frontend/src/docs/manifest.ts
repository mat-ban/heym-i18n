export function registerDocTranslations(
  locale: string,
  categories: Record<string, string>,
  titles: Record<string, string>
): void {
  CATEGORY_LABELS_BY_LOCALE[locale] = {
    ...(CATEGORY_LABELS_BY_LOCALE[locale] || {}),
    ...categories,
  };
  DOC_TITLES_BY_LOCALE[locale] = {
    ...(DOC_TITLES_BY_LOCALE[locale] || {}),
    ...titles,
  };
}

export function getDocsManifest(locale = "en"): Record<string, DocCategory> {
  const catLabels = CATEGORY_LABELS_BY_LOCALE[locale];
  const docTitles = DOC_TITLES_BY_LOCALE[locale];
  if (!catLabels && !docTitles) {
    return DOCS_MANIFEST;
  }
  const localized: Record<string, DocCategory> = {};
  for (const [catId, category] of Object.entries(DOCS_MANIFEST)) {
    localized[catId] = {
      id: category.id,
      label: catLabels?.[catId] ?? category.label,
      items: category.items.map((item) => ({
        slug: item.slug,
        title: docTitles?.[item.slug] ?? item.title,
      })),
    };
  }
  return localized;
}

export function getDocPath(categoryId: string, slug: string): string {
  return `/docs/${categoryId}/${slug}`;
}

export function getPrevNextDoc(
  currentPath: string,
  locale = "en"
): { prev: { path: string; title: string } | null; next: { path: string; title: string } | null } {
  const items = getAllDocItems({}, locale);
  const normalized = currentPath.replace(/^\//, "").replace(/\/$/, "").replace(/^docs\//, "");
  const idx = items.findIndex((i) => `${i.categoryId}/${i.slug}` === normalized);
  if (idx < 0) return { prev: null, next: null };
  const prevItem = idx > 0 ? items[idx - 1] : null;
  const nextItem = idx >= 0 && idx < items.length - 1 ? items[idx + 1] : null;
  return {
    prev: prevItem ? { path: getDocPath(prevItem.categoryId, prevItem.slug), title: prevItem.title } : null,
    next: nextItem ? { path: getDocPath(nextItem.categoryId, nextItem.slug), title: nextItem.title } : null,
  };
}

export function getAllDocItems(
  extraCategories: Record<string, DocCategory> = {},
  locale = "en"
): DocSearchItem[] {
  const items: DocSearchItem[] = [];
  const categories = { ...getDocsManifest(locale), ...extraCategories };
  for (const [categoryId, category] of Object.entries(categories)) {
    for (const item of category.items) {
      items.push({
        categoryId,
        categoryLabel: category.label,
        slug: item.slug,
        title: item.title,
      });
    }
  }
  return items;
}

